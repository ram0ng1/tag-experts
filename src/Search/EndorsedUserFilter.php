namespace Ramon\TagExperts\Search;

use Flarum\Search\Database\DatabaseSearchState;
use Flarum\Search\Filter\FilterInterface;
use Flarum\Search\SearchState;
use Flarum\Search\ValidateFilterTrait;

/**
 * `filter[user]`: as recomendações feitas a um usuário (o modal só precisa delas).
 *
 * @implements FilterInterface<DatabaseSearchState>
 */
class EndorsedUserFilter implements FilterInterface
{
    use ValidateFilterTrait;

    public function getFilterKey(): string
    {
        return 'user';
    }

    public function filter(SearchState $state, string|array $value, bool $negate): void
    {
        $state->getQuery()->whereIn('tag_expert_endorsements.user_id', $this->asIntArray($value), 'and', $negate);
    }
}
